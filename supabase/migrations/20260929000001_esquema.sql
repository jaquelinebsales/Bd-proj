-- Postgres 15+ no Supabase. Extensões ficam no schema "extensions".

create extension if not exists postgis with schema extensions;
create extension if not exists pg_trgm with schema extensions;
create extension if not exists unaccent with schema extensions;

-- Texto sem acento e em minúsculas, usado na busca. Declarada imutável para
-- poder alimentar coluna gerada e índice.
create or replace function public.normalizar(texto text)
returns text
language sql
immutable
parallel safe
set search_path = ''
as $$
  select lower(extensions.unaccent('extensions.unaccent'::regdictionary, coalesce(texto, '')))
$$;

