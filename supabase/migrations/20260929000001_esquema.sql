-- ---------------------------------------------------------------------------
-- Postos (base oficial: cadastro de revendedores da ANP)
-- ---------------------------------------------------------------------------
create table public.postos (
  id                        bigint generated by default as identity primary key,
  cnpj                      char(14) not null unique,
  razao_social              text not null,
  nome_exibicao             text,
  bandeira                  text,
  endereco                  text,
  complemento               text,
  bairro                    text,
  municipio                 text not null,
  uf                        char(2) not null,
  cep                       char(8),
  localizacao               extensions.geography(Point, 4326),
  localizacao_validada      boolean not null default false,
  localizacao_fonte         text check (localizacao_fonte in ('anp', 'geocodificacao', 'usuario')),
  autorizacao_anp           text,
  ativo                     boolean not null default true,
  municipio_pesquisado_anp  boolean not null default false,
  nota_media                numeric(3,2),
  total_avaliacoes          integer not null default 0,
  sincronizado_em           timestamptz,
  criado_em                 timestamptz not null default now(),
  texto_busca               text generated always as (
    public.normalizar(
      coalesce(nome_exibicao, '') || ' ' || razao_social || ' ' || coalesce(bandeira, '') || ' ' ||
      coalesce(endereco, '') || ' ' || coalesce(bairro, '') || ' ' || municipio || ' ' || uf
    )
  ) stored
);

create index postos_localizacao_idx on public.postos using gist (localizacao);
create index postos_busca_idx on public.postos using gin (texto_busca extensions.gin_trgm_ops);
create index postos_municipio_idx on public.postos (uf, municipio);

create table public.posto_produtos (
  posto_id    bigint not null references public.postos (id) on delete cascade,
  produto_id  smallint not null references public.produtos (id),
  bicos       smallint,
  primary key (posto_id, produto_id)
);

create table public.sincronizacoes_anp (
  uf               char(2) primary key,
  executado_em     timestamptz,
  registros        integer,
  erro             text
);

-- ---------------------------------------------------------------------------
-- Preços oficiais da ANP (últimos ~2 anos; série completa fica no Storage)
-- ---------------------------------------------------------------------------
create table public.precos_anp (
  posto_id     bigint not null references public.postos (id) on delete cascade,
  produto_id   smallint not null references public.produtos (id),
  data_coleta  date not null,
  preco        numeric(5,3) not null,
  anomalia     boolean not null default false,
  primary key (posto_id, produto_id, data_coleta)
);

-- ---------------------------------------------------------------------------
-- Usuários
-- ---------------------------------------------------------------------------
create table public.perfis (
  id                   uuid primary key references auth.users (id) on delete cascade,
  nome                 text not null check (char_length(nome) between 2 and 60),
  avatar_url           text,
  pontos               integer not null default 0,
  confiabilidade       numeric(4,3) not null default 0.500 check (confiabilidade between 0 and 1),
  bloqueado_ate        timestamptz,
  banido               boolean not null default false,
  notificacoes_ativas  boolean not null default true,
  criado_em            timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Envios da comunidade. A foto NUNCA é enviada: guardamos só o valor lido.
-- ---------------------------------------------------------------------------
create table public.envios (
  id              uuid primary key default gen_random_uuid(),
  usuario_id      uuid references public.perfis (id) on delete set null,
  posto_id        bigint not null references public.postos (id) on delete cascade,
  posicao         extensions.geography(Point, 4326) not null,
  distancia_m     integer not null,
  ocr_texto       text check (char_length(ocr_texto) <= 2000),
  ocr_duracao_ms  integer,
  app_versao      text,
  criado_em       timestamptz not null default now()
);

create index envios_usuario_idx on public.envios (usuario_id, criado_em desc);

create table public.envio_itens (
  id              bigint generated always as identity primary key,
  envio_id        uuid not null references public.envios (id) on delete cascade,
  posto_id        bigint not null references public.postos (id) on delete cascade,
  produto_id      smallint not null references public.produtos (id),
  usuario_id      uuid references public.perfis (id) on delete set null,
  preco           numeric(5,3) not null,
  preco_lido      numeric(5,3),
  confianca_ocr   real check (confianca_ocr between 0 and 1),
  editado         boolean generated always as (preco_lido is distinct from preco) stored,
  status          public.status_envio not null default 'pendente',
  em_revisao      boolean not null default false,
  motivo_revisao  text,
  consolidado_em  timestamptz,
  criado_em       timestamptz not null default now()
);

create index envio_itens_posto_idx on public.envio_itens (posto_id, produto_id, criado_em desc);
create index envio_itens_usuario_idx on public.envio_itens (usuario_id, criado_em desc);
create index envio_itens_pendentes_idx on public.envio_itens (criado_em) where status = 'pendente';

-- Histórico diário da comunidade (entra no gráfico de histórico)
create table public.precos_comunidade (
  posto_id    bigint not null references public.postos (id) on delete cascade,
  produto_id  smallint not null references public.produtos (id),
  dia         date not null,
  preco       numeric(5,3) not null,
  envios      integer not null,
  usuarios    integer not null,
  confirmado  boolean not null,
  primary key (posto_id, produto_id, dia)
);

-- Estimativa regional para postos sem nenhum preço (recalculada semanalmente)
create table public.precos_estimados (
  posto_id        bigint not null references public.postos (id) on delete cascade,
  produto_id      smallint not null references public.produtos (id),
  preco           numeric(5,3) not null,
  margem          numeric(4,2) not null,
  distancia_km    numeric(6,1) not null,
  calculado_em    timestamptz not null default now(),
  primary key (posto_id, produto_id)
);

-- Preço exibido no app: uma linha por posto e combustível
create table public.precos_atuais (
  posto_id        bigint not null references public.postos (id) on delete cascade,
  produto_id      smallint not null references public.produtos (id),
  preco           numeric(5,3) not null,
  fonte           public.fonte_preco not null,
  situacao        public.situacao_preco not null,
  atualizado_em   timestamptz not null,
  confirmacoes    integer not null default 0,
  margem          numeric(4,2),
  distancia_km    numeric(6,1),
  -- Último preço confirmado ou oficial: base para avisar quem favoritou o posto
  ultimo_confiavel numeric(5,3),
  primary key (posto_id, produto_id)
);

create index precos_atuais_produto_idx on public.precos_atuais (produto_id, preco);

-- ---------------------------------------------------------------------------
-- Avaliações, favoritos, pontos e notificações
-- ---------------------------------------------------------------------------
create table public.avaliacoes (
  id             bigint generated always as identity primary key,
  posto_id       bigint not null references public.postos (id) on delete cascade,
  usuario_id     uuid not null references public.perfis (id) on delete cascade,
  nota           smallint not null check (nota between 0 and 5),
  comentario     text check (comentario is null or char_length(comentario) between 3 and 500),
  votos_uteis    integer not null default 0,
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now(),
  unique (posto_id, usuario_id)
);

create index avaliacoes_posto_idx on public.avaliacoes (posto_id, criado_em desc);

create table public.avaliacao_votos (
  avaliacao_id  bigint not null references public.avaliacoes (id) on delete cascade,
  usuario_id    uuid not null references public.perfis (id) on delete cascade,
  criado_em     timestamptz not null default now(),
  primary key (avaliacao_id, usuario_id)
);

create table public.favoritos (
  usuario_id  uuid not null references public.perfis (id) on delete cascade,
  posto_id    bigint not null references public.postos (id) on delete cascade,
  notificar   boolean not null default true,
  criado_em   timestamptz not null default now(),
  primary key (usuario_id, posto_id)
);

create table public.pontos_movimentos (
  id             bigint generated always as identity primary key,
  usuario_id     uuid not null references public.perfis (id) on delete cascade,
  envio_item_id  bigint references public.envio_itens (id) on delete set null,
  tipo           text not null,
  pontos         integer not null,
  descricao      text not null,
  criado_em      timestamptz not null default now()
);

create index pontos_usuario_idx on public.pontos_movimentos (usuario_id, criado_em desc);

create table public.notificacoes (
  id              bigint generated always as identity primary key,
  usuario_id      uuid not null references public.perfis (id) on delete cascade,
  posto_id        bigint not null references public.postos (id) on delete cascade,
  produto_id      smallint not null references public.produtos (id),
  preco_anterior  numeric(5,3) not null,
  preco_novo      numeric(5,3) not null,
  lida            boolean not null default false,
  criado_em       timestamptz not null default now()
);

create index notificacoes_usuario_idx on public.notificacoes (usuario_id, criado_em desc);

